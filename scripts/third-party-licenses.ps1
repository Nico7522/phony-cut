# Writes THIRD_PARTY_LICENSES.md at the repository root: every third-party
# component shipped with PhoneCut (scrcpy server, adb, FFmpeg, Rust crates
# built for Windows x64), with its version, license and source.
#   powershell -ExecutionPolicy Bypass -File scripts\third-party-licenses.ps1
#
# The file is committed (the website and the README link to it), shipped by the
# installer and shown in the app's About section (embedded at compile time).
# CI regenerates it and fails if it differs: rerun this script and commit the
# result after changing a dependency or a file in vendor/.
# Versions are read from scripts/fetch-ffmpeg.ps1 and vendor/VERSIONS.md.

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$Out = Join-Path $Root 'THIRD_PARTY_LICENSES.md'

function Get-Match([string]$Text, [string]$Pattern, [string]$What) {
    $m = [regex]::Match($Text, $Pattern)
    if (-not $m.Success) { throw "Cannot find $What" }
    $m.Groups[1].Value
}

$fetch = Get-Content (Join-Path $Root 'scripts\fetch-ffmpeg.ps1') -Raw
$ffRelease = Get-Match $fetch "\`$Release = '([^']+)'" 'the FFmpeg release in fetch-ffmpeg.ps1'
$ffArchive = Get-Match $fetch "\`$Archive = '([^']+)'" 'the FFmpeg archive in fetch-ffmpeg.ps1'
$ffVersion = Get-Match $ffArchive '^ffmpeg-(n[^-]+(?:-\d+-g[0-9a-f]+)?)' 'the FFmpeg version'
$ffCommit = Get-Match $ffArchive '-g([0-9a-f]+)-' 'the FFmpeg commit'

$versions = Get-Content (Join-Path $Root 'vendor\VERSIONS.md') -Raw
$scrcpy = Get-Match $versions 'scrcpy-server` \| \*\*(v[0-9.]+)\*\*' 'the scrcpy version in VERSIONS.md'
$tools = Get-Match $versions 'Platform-Tools \*\*([0-9.]+)\*\*' 'the platform-tools version in VERSIONS.md'

Push-Location $Root
try {
    $json = cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc
    if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
} finally {
    Pop-Location
}
$meta = $json | ConvertFrom-Json

$members = @{}
foreach ($id in $meta.workspace_members) { $members[$id] = $true }
$used = @{}
foreach ($node in $meta.resolve.nodes) { $used[$node.id] = $true }

# Ordinal sort: the same order on every machine (CI checks the file), whatever
# the Windows language and the PowerShell edition.
$packages = [object[]]@($meta.packages | Where-Object { $used[$_.id] -and -not $members[$_.id] })
$keys = [string[]]@($packages | ForEach-Object { "$($_.name) $($_.version)" })
[Array]::Sort($keys, $packages, [StringComparer]::Ordinal)
$crates = @($packages |
    ForEach-Object {
        $license = if ($_.license) { $_.license } elseif ($_.license_file) { "see $($_.license_file)" } else { 'not specified' }
        $repo = if ($_.repository) { $_.repository } else { '' }
        "| $($_.name) | $($_.version) | $license | $repo |"
    })

$lines = @(
    '# Third-party licenses',
    '',
    'PhoneCut itself is licensed under MIT OR Apache-2.0 (`LICENSE-MIT`, `LICENSE-APACHE`).',
    'It ships the following third-party components. Their license texts are in',
    '`vendor/licenses/` (installed next to PhoneCut).',
    '',
    '_This file is generated by `scripts/third-party-licenses.ps1`: do not edit it by hand._',
    '',
    '## scrcpy server',
    '',
    "- Version: $scrcpy, file ``vendor/scrcpy/scrcpy-server``, runs on the phone.",
    '- Copyright Genymobile and Romain Vimont.',
    '- License: Apache License 2.0 (`vendor/licenses/scrcpy-LICENSE-Apache-2.0.txt`).',
    '- Source: https://github.com/Genymobile/scrcpy',
    '',
    '## Android SDK Platform-Tools (adb)',
    '',
    "- Version: $tools, files ``vendor/adb/adb.exe``, ``AdbWinApi.dll``, ``AdbWinUsbApi.dll``.",
    '- Copyright The Android Open Source Project.',
    '- License: see `vendor/licenses/platform-tools-NOTICE.txt` (mostly Apache License 2.0).',
    '- Source: https://android.googlesource.com/platform/packages/modules/adb/',
    '',
    '## FFmpeg',
    '',
    "- Version: $ffVersion, Windows x64 LGPL shared build ``$ffArchive``.",
    '- License: GNU Lesser General Public License 2.1 or later',
    '  (`vendor/licenses/ffmpeg-LICENSE-LGPL.txt`). The build contains no GPL or non-free part.',
    '- PhoneCut uses FFmpeg as separate DLLs (`avcodec`, `avformat`, `avutil`, `swscale`…, next',
    '  to `phonecut.exe`), linked dynamically: you can replace them with your own build of the',
    '  same major version.',
    "- Source code of this exact version: https://github.com/FFmpeg/FFmpeg/tree/$ffCommit",
    '  (official repository: https://git.ffmpeg.org/ffmpeg.git).',
    "- Build scripts and the list of included libraries: https://github.com/BtbN/FFmpeg-Builds",
    "  (release ``$ffRelease``). It includes OpenH264 (Cisco, BSD 2-Clause), used to re-encode",
    '  the edges of clips in precise export.',
    '',
    "## Rust libraries ($($crates.Count))",
    '',
    'Built into `phonecut.exe`. The text of each license is in the repository of the library.',
    '',
    '| Library | Version | License | Repository |',
    '| --- | --- | --- | --- |'
) + $crates

[IO.File]::WriteAllLines($Out, $lines, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $Out ($($crates.Count) Rust crates)"
